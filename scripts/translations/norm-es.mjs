const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// Only match on letter boundaries so 'dés' can't hit inside 'désossé',
// 'eau' can't hit inside 'peau', etc. Sources ending in "'" look ahead for a letter.
const RULES = PHRASES.map(([src, dst]) => {
  let pat = '';
  if (/^[\p{L}]/u.test(src)) pat += '(?<![\\p{L}])';
  pat += esc(src);
  if (src.endsWith("'")) pat += '(?=\\p{L})';
  else if (/[\p{L}]$/u.test(src)) pat += '(?![\\p{L}])';
  return [new RegExp(pat, 'gu'), dst];
});

function translate(v) {
  let out = ' ' + v + ' ';
  for (const [re, dst] of RULES) out = out.replace(re, dst);
  return out.trim().replace(/\s+/g, ' ');
}

const es = { exact: {}, numbers: {}, units: {}, mods: {} };
const leftover = [];
for (const sec of ['exact', 'numbers', 'units', 'mods']) {
  for (const [k, v] of Object.entries(fr[sec])) {
    const t = translate(v);
    es[sec][k] = t;
    if (/[àâçéèêëîïôùûœ]|tasse|c\.|pinc|oignon|poulet|feuille|morceau|sachet|boîte|bocal|botte|brin|bâton|gousse|pièce|tranche|rouleau|boule|galette|tarte|sandwich|œuf|citron|goût|facultatif|haché|râpé|coupé|désossé|bouill|séch|mois|jour|semaine|personne/i.test(t)) {
      leftover.push(`${sec}\t${k}\t${v}\t=>\t${t}`);
    }
  }
}
