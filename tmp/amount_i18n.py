_cache = {}
def _pattern(lang):
    if lang not in _cache:
        keys = sorted((k for k, _ in PHRASES[lang]), key=len, reverse=True)
        alt = "|".join(re.escape(k) for k in keys)
        _cache[lang] = (re.compile(r"(?<![A-Za-z])(" + alt + r")(?![A-Za-z])", re.IGNORECASE),
                        {k.lower(): v for k, v in PHRASES[lang]})
    return _cache[lang]

def translate(lang, s):
    rx, lut = _pattern(lang)
    out = rx.sub(lambda m: lut[m.group(0).lower()], s.strip())
    for u, tr in UNITS[lang]:
        out = re.sub(r'(?<![^\W\d_])' + re.escape(u) + r'(?![^\W\d_])', tr, out)
    return re.sub(r'\s+', ' ', out).strip()

