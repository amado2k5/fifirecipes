export function detectUserLocale(): { language: SupportedLanguage; isKnown: boolean; rawLocale: string } {
  try {
    const rawLocale = (typeof navigator !== 'undefined' && ((navigator.languages && navigator.languages[0]) || navigator.language)) || '';
    if (!rawLocale) {
      // Default to Arabic if user locale is not being detected
      return { language: 'en', isKnown: false, rawLocale: '' };
    }
    const primaryCode = rawLocale.split('-')[0].toLowerCase() as SupportedLanguage;
    if (primaryCode === 'ar') {
      return { language: 'ar', isKnown: true, rawLocale };
    }
    if (primaryCode === 'fr') {
      return { language: 'fr', isKnown: true, rawLocale };
    }
    if (primaryCode === 'es') {
      return { language: 'es', isKnown: true, rawLocale };
    }
    if (primaryCode === 'ja') {
      return { language: 'ja', isKnown: true, rawLocale };
    }
    if (primaryCode === 'hi') {
      return { language: 'hi', isKnown: true, rawLocale };
    }
    if (primaryCode === 'pt') {
      return { language: 'pt', isKnown: true, rawLocale };
    }
    if (primaryCode === 'ru') {
      return { language: 'ru', isKnown: true, rawLocale };
    }
    if (primaryCode === 'zh') {
      return { language: 'zh', isKnown: true, rawLocale };
    }
    if (primaryCode === 'de') {
      return { language: 'de', isKnown: true, rawLocale };
    }
    if (primaryCode === 'it') {
      return { language: 'it', isKnown: true, rawLocale };
    }
    if (primaryCode === 'el') {
      return { language: 'el', isKnown: true, rawLocale };
    }
    if (primaryCode === 'ur') {
      return { language: 'ur', isKnown: true, rawLocale };
    }
    if (primaryCode === 'fa') {
      return { language: 'fa', isKnown: true, rawLocale };
    }
    if (primaryCode === 'tr') {
      return { language: 'tr', isKnown: true, rawLocale };
    }
    if (primaryCode === 'ku' || (primaryCode as string) === 'kmr') {
      return { language: 'ku', isKnown: true, rawLocale };
    }
    if (primaryCode === 'id' || (primaryCode as string) === 'in') {
      return { language: 'id', isKnown: true, rawLocale };
    }
    return { language: 'en', isKnown: true, rawLocale };
  } catch {
    return { language: 'en', isKnown: false, rawLocale: '' };
  }
}

export function detectUserLanguage(): SupportedLanguage {
  return detectUserLocale().language;
}


